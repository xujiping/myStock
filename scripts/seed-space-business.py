def main():
    conn = pymysql.connect(**DB_CONFIG)
    cursor = conn.cursor(pymysql.cursors.DictCursor)
    
    try:
        # 获取所有公司
        cursor.execute("SELECT id, stock_code, company_name FROM aero_company WHERE is_active=1")
        companies = {row["stock_code"]: row for row in cursor.fetchall()}
        
        # 获取所有二级板块 sector_id
        cursor.execute("SELECT id, sector_code, sector_name FROM aero_space_sector WHERE sector_level=2 AND is_active=1")
        sectors = {row["sector_code"]: row for row in cursor.fetchall()}
        
        print(f"数据库中有 {len(companies)} 个活跃公司，{len(sectors)} 个活跃二级板块。")
        
        # 检查是否有已存在数据
        cursor.execute("SELECT COUNT(*) AS cnt FROM aero_company_space_profile")
        existing_profiles = cursor.fetchone()["cnt"]
        cursor.execute("SELECT COUNT(*) AS cnt FROM aero_company_space_business")
        existing_businesses = cursor.fetchone()["cnt"]
        
        if existing_profiles > 0 or existing_businesses > 0:
            print(f"⚠️ 数据库中已有 {existing_profiles} 条画像记录，{existing_businesses} 条业务关联记录。")
            print("继续执行将新增/更新数据...")
        
        # 行业板块→sector_id 映射（方便查找）
        sector_by_code = {}
        for s in sectors.values():
            sector_by_code[s["sector_code"]] = s["id"]
        
        # 统计
        profile_count = 0
        business_count = 0
        skipped = 0
        errors = []
        
        for stock_code, (profile_info, business_list) in COMPANY_MAP.items():
            if stock_code not in companies:
                skipped += 1
                print(f"  ⚠️ 跳过 {stock_code}：不在活动公司列表中")
                continue
            
            company = companies[stock_code]
            company_id = company["id"]
            company_name = company["company_name"]
            
            try:
                # 1. 写入/更新公司画像
                if profile_info:
                    summary = profile_info.get("business_summary", "")
                    cursor.execute("""
                        INSERT INTO aero_company_space_profile 
                            (company_id, commercial_revenue_state, commercial_revenue_confidence, 
                             business_summary, source_name, source_date, updated_by, is_manual_confirmed)
                        VALUES (%s, '公开资料推算', '中', %s, %s, %s, %s, 0)
                        ON DUPLICATE KEY UPDATE
                            business_summary=VALUES(business_summary),
                            source_name=VALUES(source_name),
                            source_date=VALUES(source_date),
                            updated_by=VALUES(updated_by)
                    """, (company_id, summary, SOURCE_NAME, SOURCE_DATE, UPDATED_BY))
                    profile_count += 1
                
                # 2. 写入业务关联
                for entry in business_list:
                    (sector_id, role, data_state, confidence, chain_desc,
                     rev_min, rev_max, comp_rev_min, comp_rev_max,
                     chain_imp, comp_imp, research_note) = entry
                    
                    # sector_id可能传的是 sector_code，需要转成数字ID
                    if isinstance(sector_id, str):
                        if sector_id in sector_by_code:
                            sector_id = sector_by_code[sector_id]
                        else:
                            print(f"  ⚠️ {stock_code} ({company_name})：未找到板块代码 {sector_id}")
                            continue
                    
                    cursor.execute("""
                        INSERT INTO aero_company_space_business
                            (company_id, sector_id, business_role, business_status, data_state, confidence,
                             space_revenue_min, space_revenue_max, 
                             company_revenue_min, company_revenue_max,
                             chain_scope, chain_importance, company_importance,
                             research_note, source_name, source_date, is_current)
                        VALUES (%s, %s, %s, '当前', %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 1)
                    """, (
                        company_id, sector_id, role, data_state, confidence,
                        rev_min, rev_max, comp_rev_min, comp_rev_max,
                        chain_desc, chain_imp, comp_imp,
                        research_note, SOURCE_NAME, SOURCE_DATE,
                    ))
                    business_count += 1
                
                if business_list:
                    print(f"  ✅ {stock_code} {company_name}: {len(business_list)} 条业务关联")
                else:
                    print(f"  ✅ {stock_code} {company_name}: 已跳过（无业务关联）")
                    
            except Exception as e:
                errors.append(f"{stock_code} ({company_name}): {e}")
                print(f"  ❌ {stock_code} {company_name}: 错误 - {e}")
        
        conn.commit()
        
        print(f"\n{'='*60}")
        print(f"写入完成！")
        print(f"  公司画像写入/更新: {profile_count} 条")
        print(f"  业务关联写入: {business_count} 条")
        print(f"  跳过（不在列表）: {skipped} 家")
        if errors:
            print(f"  错误: {len(errors)} 个")
            for e in errors[:5]:
                print(f"    - {e}")
        print(f"{'='*60}")
        
    finally:
        cursor.close()
        conn.close()


if __name__ == "__main__":
    # 检查 pymysql 是否安装
    try:
        import pymysql
    except ImportError:
        print("请先安装 pymysql: pip install pymysql python-dotenv")
        sys.exit(1)
    
    main()
